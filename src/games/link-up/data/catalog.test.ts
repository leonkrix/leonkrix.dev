import { describe, expect, it } from 'vitest';

import { catalog } from './catalog';
import { categories, shardCategories } from './index';
import { shardLoaders } from './shards';

/**
 * The text of `catalog.ts`: a list of every category with the file it lives in, so that the game
 * can choose categories without loading all of them. After adding or moving a category, update it
 * with: pnpm exec vitest run src/games/link-up/data/catalog.test.ts -u
 */
function catalogText(): string {
  const lines = Object.entries(shardCategories).flatMap(([shard, list]) =>
    list.map((category) => `  ['${category.id}', '${shard}'],`),
  );
  return [
    "import { type ShardId } from './shards';",
    '',
    '/**',
    ' * Every category with the file (shard) it lives in, in the order of `shardCategories`.',
    ' * Generated by catalog.test.ts, do not edit by hand.',
    ' */',
    'export const catalog: readonly (readonly [id: string, shard: ShardId])[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

describe('the catalog of Link Up', () => {
  it('lists every category with its file (update it with the command in catalog.test.ts)', async () => {
    await expect(catalogText()).toMatchFileSnapshot('./catalog.ts');
  });

  it('has the same categories in the same order as the data', () => {
    expect(catalog.map(([id]) => id)).toEqual(categories.map((category) => category.id));
  });

  it('knows the same files as the loaders', () => {
    expect(Object.keys(shardLoaders)).toEqual(Object.keys(shardCategories));
  });

  it('loads every category from the file the catalog names', async () => {
    for (const [shard, loader] of Object.entries(shardLoaders)) {
      const loaded = await loader();
      const listed = catalog.filter(([, name]) => name === shard).map(([id]) => id);
      expect(
        loaded.map((category) => category.id),
        shard,
      ).toEqual(listed);
    }
  });
});
